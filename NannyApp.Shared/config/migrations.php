<?php
/**
 * Apply the versioned schema on either MariaDB or PostgreSQL.
 *
 * The source migrations remain MariaDB-shaped for backwards compatibility;
 * PostgreSQL receives a conservative DDL translation at execution time.
 * DML/query portability is handled separately by the runtime query layer.
 */
function migrate_application(PDO $pdo): void
{
    $isPostgres = defined('DB_DRIVER') && DB_DRIVER === 'pgsql';
    $name = $pdo->query($isPostgres ? 'SELECT current_database()' : 'SELECT DATABASE()')->fetchColumn();
    if (!$name) throw new RuntimeException('Select a database before migration.');
    $lock = 'nanny-migrate-' . substr(hash('sha256', $name), 0, 40);
    if ($isPostgres) {
        $pdo->prepare('SELECT pg_advisory_lock(hashtext(?))')->execute([$lock]);
    } else {
        $stmt = $pdo->prepare('SELECT GET_LOCK(?, 0)');
        $stmt->execute([$lock]);
        if ((int) $stmt->fetchColumn() !== 1) throw new RuntimeException('Another migration is running.');
    }
    try {
        if (!$isPostgres) {
            $pdo->exec("SET SESSION sql_mode='STRICT_ALL_TABLES,NO_ZERO_DATE,NO_ZERO_IN_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION'");
        }
        $pdo->exec('CREATE TABLE IF NOT EXISTS schema_migrations (name VARCHAR(100) PRIMARY KEY, checksum CHAR(64) NOT NULL, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)' . ($isPostgres ? '' : ' ENGINE=InnoDB'));
        $files = ['schema.sql','migrate_v2.sql','migrate_v3.sql','migrate_v4.sql','migrate_v5_api.sql','phase1_constraints.sql','phase2_authentication.sql','migrate_v6_security.sql','migrate_v7_email_outbox.sql','migrate_v8_operations.sql','migrate_v9_reports_holidays.sql','migrate_v10_plus_translation.sql','migrate_v11_deliverables.sql','migrate_v12_sessions_downloads.sql'];
        foreach ($files as $file) {
            $sql = file_get_contents(__DIR__ . '/../database/' . $file);
            if ($sql === false) throw new RuntimeException('Missing migration: ' . $file);
            $hash = hash('sha256', str_replace("\r\n", "\n", $sql));
            $stmt = $pdo->prepare('SELECT checksum FROM schema_migrations WHERE name=?');
            $stmt->execute([$file]);
            $existing = $stmt->fetchColumn();
            if ($existing !== false) {
                if (!hash_equals($existing, $hash)) throw new RuntimeException('Applied migration changed: ' . $file);
                continue;
            }
            // These reviewed files contain DDL only, no procedures or semicolons in strings.
            $sql = preg_replace('/--[^\r\n]*/', '', $sql);
            foreach (explode(';', $sql) as $statement) {
                $statement = trim($statement);
                if ($statement === '') continue;
                if (!preg_match('/^(CREATE TABLE IF NOT EXISTS|CREATE INDEX IF NOT EXISTS|ALTER TABLE)\b/i', $statement)) {
                    throw new RuntimeException('Non-schema statement refused in ' . $file);
                }
                foreach ($isPostgres ? postgres_migration_statements($statement) : [$statement] as $portableStatement) {
                    if (trim($portableStatement) !== '') $pdo->exec($portableStatement);
                }
            }
            $pdo->prepare('INSERT INTO schema_migrations (name,checksum) VALUES (?,?)')->execute([$file,$hash]);
        }
    } finally {
        if ($isPostgres) {
            $pdo->prepare('SELECT pg_advisory_unlock(hashtext(?))')->execute([$lock]);
        } else {
            $pdo->prepare('SELECT RELEASE_LOCK(?)')->execute([$lock]);
        }
    }
}

/** @return list<string> */
function postgres_migration_statements(string $statement): array
{
    $statement = preg_replace('/\bENGINE\s*=\s*\w+/i', '', $statement) ?? $statement;
    $statement = preg_replace('/\bAUTO_INCREMENT\b/i', 'GENERATED BY DEFAULT AS IDENTITY', $statement) ?? $statement;
    $statement = preg_replace('/\bTINYINT\s*\(\s*1\s*\)/i', 'SMALLINT', $statement) ?? $statement;
    $statement = preg_replace('/\bTINYINT\b/i', 'SMALLINT', $statement) ?? $statement;
    $statement = preg_replace('/\b(?:TINYINT|SMALLINT|MEDIUMINT|INT|INTEGER)\s+UNSIGNED\b/i', 'INTEGER', $statement) ?? $statement;
    $statement = preg_replace('/\bBIGINT\s+UNSIGNED\b/i', 'BIGINT', $statement) ?? $statement;
    $statement = preg_replace('/\b(?:DATETIME|TIMESTAMP)\b/i', 'TIMESTAMP', $statement) ?? $statement;
    $statement = preg_replace('/\bMEDIUMTEXT\b/i', 'TEXT', $statement) ?? $statement;
    $statement = preg_replace('/\bENUM\s*\([^)]*\)/i', 'VARCHAR(32)', $statement) ?? $statement;
    $statement = preg_replace('/\s+COMMENT\s+\'[^\']*\'/i', '', $statement) ?? $statement;
    $statement = preg_replace('/\s+CHARACTER\s+SET\s+\w+/i', '', $statement) ?? $statement;
    $statement = preg_replace('/\s+COLLATE\s+\w+/i', '', $statement) ?? $statement;
    $statement = preg_replace('/\s+DEFAULT\s+CHARSET\s*=\s*\w+/i', '', $statement) ?? $statement;
    $statement = preg_replace('/\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP\b/i', '', $statement) ?? $statement;
    $statement = preg_replace('/\s+AFTER\s+`?[a-zA-Z_][a-zA-Z0-9_]*`?/i', '', $statement) ?? $statement;

    // Inline MySQL indexes in CREATE TABLE are recreated by the additive
    // constraint migrations, and PostgreSQL does not support this syntax.
    $statement = preg_replace('/,\s*(?:UNIQUE\s+)?(?:INDEX|KEY)\s+`?[a-zA-Z_][a-zA-Z0-9_]*`?\s*\([^)]*\)/i', '', $statement) ?? $statement;

    // MySQL uses MODIFY to restate an existing column type. The PostgreSQL
    // schema already uses VARCHAR for translated ENUM columns, so the
    // widening status change is intentionally a no-op there.
    if (preg_match('/^ALTER\s+TABLE\b.*\bMODIFY\s+COLUMN\b/is', trim($statement))) return [];

    // MySQL's ALTER TABLE ... ADD [UNIQUE] KEY is equivalent to a PostgreSQL
    // index for the application's uniqueness and lookup requirements.
    if (preg_match('/^ALTER\s+TABLE\s+`?([a-zA-Z_][a-zA-Z0-9_]*)`?\s+(.+)$/is', trim($statement), $match)) {
        $table = $match[1];
        $actions = [];
        preg_match_all('/ADD\s+(UNIQUE\s+)?(?:KEY|INDEX)\s+(?:IF\s+NOT\s+EXISTS\s+)?`?([a-zA-Z_][a-zA-Z0-9_]*)`?\s*\(([^)]*)\)/i', $match[2], $indexes, PREG_SET_ORDER);
        foreach ($indexes as $index) {
            $unique = trim((string)$index[1]) !== '' ? 'UNIQUE ' : '';
            $actions[] = sprintf('CREATE %sINDEX IF NOT EXISTS %s ON %s (%s)', $unique, $index[2], $table, $index[3]);
        }
        if ($actions !== []) return $actions;
    }

    return [trim($statement)];
}

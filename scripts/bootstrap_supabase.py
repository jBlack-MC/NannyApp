"""Bootstrap the Nanny-App PostgreSQL/Supabase database.

Credentials are read from environment variables and are never stored in the
repository. The SQL translation mirrors NannyApp.Shared/config/migrations.php.
"""
from __future__ import annotations

import hashlib
import os
import re
from pathlib import Path

import psycopg2

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "NannyApp.Shared" / "database"
FILES = [
    "schema.sql", "migrate_v2.sql", "migrate_v3.sql", "migrate_v4.sql",
    "migrate_v5_api.sql", "phase1_constraints.sql", "phase2_authentication.sql",
    "migrate_v6_security.sql", "migrate_v7_email_outbox.sql",
    "migrate_v8_operations.sql", "migrate_v9_reports_holidays.sql",
    "migrate_v10_plus_translation.sql",
]


def pg_statement(sql: str) -> list[str]:
    sql = re.sub(r"\bENGINE\s*=\s*\w+", "", sql, flags=re.I)
    sql = re.sub(r"\bAUTO_INCREMENT\b", "GENERATED BY DEFAULT AS IDENTITY", sql, flags=re.I)
    sql = re.sub(r"\bTINYINT\s*\(\s*1\s*\)", "SMALLINT", sql, flags=re.I)
    sql = re.sub(r"\bTINYINT\b", "SMALLINT", sql, flags=re.I)
    sql = re.sub(r"\b(?:TINYINT|SMALLINT|MEDIUMINT|INT|INTEGER)\s+UNSIGNED", "INTEGER", sql, flags=re.I)
    sql = re.sub(r"\bBIGINT\s+UNSIGNED", "BIGINT", sql, flags=re.I)
    sql = re.sub(r"\b(?:DATETIME|TIMESTAMP)\b", "TIMESTAMP", sql, flags=re.I)
    sql = re.sub(r"\bMEDIUMTEXT\b", "TEXT", sql, flags=re.I)
    sql = re.sub(r"\bENUM\s*\([^)]*\)", "VARCHAR(32)", sql, flags=re.I)
    sql = re.sub(r"\s+COMMENT\s+'[^']*'", "", sql, flags=re.I)
    sql = re.sub(r"\s+CHARACTER\s+SET\s+\w+", "", sql, flags=re.I)
    sql = re.sub(r"\s+COLLATE\s+\w+", "", sql, flags=re.I)
    sql = re.sub(r"\s+DEFAULT\s+CHARSET\s*=\s*\w+", "", sql, flags=re.I)
    sql = re.sub(r"\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP\b", "", sql, flags=re.I)
    sql = re.sub(r"\s+AFTER\s+`?[A-Za-z_][A-Za-z0-9_]*`?", "", sql, flags=re.I)
    sql = re.sub(r",\s*(?:UNIQUE\s+)?(?:INDEX|KEY)\s+`?[A-Za-z_][A-Za-z0-9_]*`?\s*\([^)]*\)", "", sql, flags=re.I)
    if re.search(r"^\s*ALTER\s+TABLE\b.*\bMODIFY\s+COLUMN\b", sql, flags=re.I | re.S):
        return []
    m = re.match(r"^\s*ALTER\s+TABLE\s+`?([A-Za-z_][A-Za-z0-9_]*)`?\s+(.+)$", sql, flags=re.I | re.S)
    if m:
        actions = []
        for ix in re.finditer(r"ADD\s+(UNIQUE\s+)?(?:KEY|INDEX)\s+(?:IF\s+NOT\s+EXISTS\s+)?`?([A-Za-z_][A-Za-z0-9_]*)`?\s*\(([^)]*)\)", m.group(2), flags=re.I):
            unique = "UNIQUE " if ix.group(1) else ""
            actions.append(f"CREATE {unique}INDEX IF NOT EXISTS {ix.group(2)} ON {m.group(1)} ({ix.group(3)})")
        if actions:
            return actions
    return [sql.strip()]


def main() -> None:
    conn = psycopg2.connect(
        host=os.environ.get("NANNYAPP_DB_HOST", "aws-0-us-east-1.pooler.supabase.com"),
        port=os.environ.get("NANNYAPP_DB_PORT", "5432"),
        dbname=os.environ.get("NANNYAPP_DB_NAME", "postgres"),
        user=os.environ["NANNYAPP_DB_USER"],
        password=os.environ["NANNYAPP_DB_PASS"],
        sslmode="require",
    )
    conn.autocommit = True
    cur = conn.cursor()
    cur.execute("CREATE TABLE IF NOT EXISTS schema_migrations (name VARCHAR(100) PRIMARY KEY, checksum CHAR(64) NOT NULL, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)")
    for name in FILES:
        raw = (DB / name).read_text(encoding="utf-8").replace("\r\n", "\n")
        checksum = hashlib.sha256(raw.encode()).hexdigest()
        cur.execute("SELECT checksum FROM schema_migrations WHERE name=%s", (name,))
        existing = cur.fetchone()
        if existing:
            if existing[0] != checksum:
                raise RuntimeError(f"Applied migration changed: {name}")
            continue
        for statement in re.split(r";", re.sub(r"--[^\r\n]*", "", raw)):
            statement = statement.strip()
            if not statement:
                continue
            if not re.match(r"^(CREATE TABLE IF NOT EXISTS|CREATE INDEX IF NOT EXISTS|ALTER TABLE)\b", statement, re.I):
                raise RuntimeError(f"Refused non-schema statement in {name}: {statement[:80]}")
            for portable in pg_statement(statement):
                if portable:
                    cur.execute(portable)
        cur.execute("INSERT INTO schema_migrations (name, checksum) VALUES (%s, %s)", (name, checksum))
        print(f"applied {name}")

    # bcrypt is compatible with PHP password_hash(..., PASSWORD_DEFAULT).
    import bcrypt
    password_hash = bcrypt.hashpw(b"Password123!", bcrypt.gensalt()).decode()
    demos = [
        ("Demo Parent", "parent@nanny.app", "parent"),
        ("Demo Nanny", "amelia@nanny.app", "nanny"),
        ("Demo Admin", "admin@nanny.app", "admin"),
    ]
    for full_name, email, role in demos:
        cur.execute("""INSERT INTO users (full_name,email,password_hash,role,email_verified,status)
                       VALUES (%s,%s,%s,%s,1,'active')
                       ON CONFLICT (email) DO UPDATE SET password_hash=EXCLUDED.password_hash,
                         email_verified=1, status='active'""", (full_name, email, password_hash, role))

    # A small repeatable dataset makes the deployed prototype demonstrable
    # without relying on hand-created records in the dashboard.
    parent_ids = []
    for i in range(1, 11):
        email = f"demo.parent{i}@nanny.app"
        cur.execute("""INSERT INTO users (full_name,email,password_hash,role,email_verified,status)
                       VALUES (%s,%s,%s,'parent',1,'active')
                       ON CONFLICT (email) DO UPDATE SET password_hash=EXCLUDED.password_hash,
                         email_verified=1, status='active'""", (f"Demo Parent {i}", email, password_hash))
        cur.execute("SELECT id FROM users WHERE email=%s", (email,))
        uid = cur.fetchone()[0]
        parent_ids.append(uid)
        cur.execute("""INSERT INTO parent_profiles (user_id, emergency_contact, number_of_children)
                       VALUES (%s,%s,%s) ON CONFLICT (user_id) DO NOTHING""", (uid, f"+27 82 555 {i:04d}", 1))
        cur.execute("""INSERT INTO children (parent_id,name,age,gender,allergies,medical_conditions,special_needs,
                       favourite_activities,notes_for_nannies) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)
                       ON CONFLICT DO NOTHING""", (uid, f"Demo Child {i}", 3 + i % 8, "prefer_not_to_say", "None", "None", "None", "Reading and outdoor play", "Demo data"))

    for i in range(1, 11):
        email = f"demo.nanny{i}@nanny.app"
        cur.execute("""INSERT INTO users (full_name,email,password_hash,role,email_verified,status)
                       VALUES (%s,%s,%s,'nanny',1,'active')
                       ON CONFLICT (email) DO UPDATE SET password_hash=EXCLUDED.password_hash,
                         email_verified=1, status='active'""", (f"Demo Nanny {i}", email, password_hash))
        cur.execute("SELECT id FROM users WHERE email=%s", (email,))
        uid = cur.fetchone()[0]
        cur.execute("""INSERT INTO nanny_profiles (user_id,bio,experience_years,hourly_rate,location,skills,
                       availability,verification_status,average_rating,languages,qualifications)
                       VALUES (%s,%s,%s,%s,%s,%s,%s,'verified',%s,%s,%s)
                       ON CONFLICT (user_id) DO NOTHING""", (uid, "Reliable childcare professional for the Nanny-App demo.", 2 + i, 85 + i * 5, "Johannesburg", "First Aid,Homework Assistance", "Weekdays", 4.0 + (i % 10) / 10, "English", "Demo qualification"))
        cur.execute("""INSERT INTO nanny_availability (nanny_id,day_of_week,is_available,time_start,time_end)
                       VALUES (%s,1,1,'08:00','17:00') ON CONFLICT DO NOTHING""", (uid,))
    cur.close()
    conn.close()
    print("demo accounts ready: parent@nanny.app, amelia@nanny.app, admin@nanny.app")


if __name__ == "__main__":
    main()
